// Which lines of Extended Mode's models and stages the current port can read.
//
//   node web/tools/ext-inventory.mjs > research/extended-mode/inventory.md
//
// A parser "reads" a line if the line starts with one of the prefixes it tests
// with startsWith -- the same test ContO / loadstage apply. The port's
// prefixes come from web/ContO.js and web/GameSparker.js, Extended's from its
// decompiled ContO.java and GameSparker.java. Lines neither reads are listed
// too: they are comments, blank-ish, or dead directives the jar ignores.

import fs from 'node:fs';
import { parseRadq } from '../ext/radq.js';
import { parseZip } from '../vfs.js';

const ROOT = new URL('../../', import.meta.url);
const text = (p) => fs.readFileSync(new URL(p, ROOT), 'utf8');
const prefixes = (src) => [...new Set([...src.matchAll(/startsWith\((['"])(.*?)\1\)/g)].map((m) => m[2]))];

const PARSERS = {
  models: {
    // the port also reads car stats from models (CarDefine); Extended has no
    // CarDefine -- its physics(...) lines are dead, stats are hardcoded
    port: [...prefixes(text('web/ContO.js')), ...prefixes(text('web/CarDefine.js'))],
    ext: prefixes(text('decompilation/extended/java-src/ContO.java')),
  },
  stages: {
    port: prefixes(text('web/GameSparker.js')),
    ext: prefixes(text('decompilation/extended/java-src/GameSparker.java')),
  },
};

const reads = (list, line) => list.some((p) => line.startsWith(p));
const directive = (line) => (line.match(/^<\/?\w+>|^[A-Za-z0-9_]+/) || ['(other)'])[0];

async function unpack(file) {
  return parseRadq(new Uint8Array(fs.readFileSync(new URL('ext/data/' + file, ROOT))));
}

function survey(kind, files) {
  const { port, ext } = PARSERS[kind];
  const rows = new Map();   // directive -> {lines, files:Set, port, ext}
  for (const [name, bytes] of files) {
    for (const raw of new TextDecoder().decode(bytes).split(/\r?\n/)) {
      const line = raw.trim();
      if (!line) continue;
      const d = directive(line);
      const r = rows.get(d) || { lines: 0, files: new Set(), port: true, ext: true };
      r.lines++;
      r.files.add(name);
      r.port &&= reads(port, line);
      r.ext &&= reads(ext, line);
      rows.set(d, r);
    }
  }
  return [...rows].sort((a, b) => b[1].lines - a[1].lines);
}

function table(title, rows) {
  const out = [`### ${title}`, '', '| directive | lines | files | port reads it | Extended reads it |', '| --- | --- | --- | --- | --- |'];
  for (const [d, r] of rows) {
    out.push(`| \`${d}\` | ${r.lines} | ${r.files.size} | ${r.port ? 'yes' : '**no**'} | ${r.ext ? 'yes' : 'no'} |`);
  }
  return out.join('\n');
}

const models = await unpack('models.radq');
const packs = ['Files/tracks.radq', 'Files/classictracks.radq', 'Files/matchtracks.radq', 'Files/careertracks.radq'];
const stages = new Map();
for (const p of packs) for (const [n, b] of await unpack(p)) if (n.endsWith('.txt')) stages.set(`${p.split('/')[1]}:${n}`, b);

const baseModels = new Set((await parseZip(new Uint8Array(fs.readFileSync(new URL('data/models.zip', ROOT))))).keys());
const newModels = [...models.keys()].filter((n) => !baseModels.has(n)).sort();

const mrows = survey('models', models);
const srows = survey('stages', stages);
const gap = (rows) => rows.filter(([, r]) => !r.port && r.ext).map(([d]) => '`' + d + '`');

console.log(`# Extended Mode inventory against the current port

Generated by \`web/tools/ext-inventory.mjs\` from \`ext/data/\`. "Reads it" means
some line of that directive starts with a prefix the parser tests.

- **${models.size} models**, ${newModels.length} not in the base game's \`data/models.zip\`.
- **${stages.size} stages** across ${packs.length} packs (${packs.map((p) => p.split('/')[1]).join(', ')}).
- **To port, models:** ${gap(mrows).join(', ') || 'nothing'}
- **To port, stages:** ${gap(srows).join(', ') || 'nothing'}

${table('Model directives', mrows)}

${table('Stage directives', srows)}

### Models new in Extended

${newModels.map((n) => '`' + n + '`').join(' ')}
`);
